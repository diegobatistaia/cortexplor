#!/usr/bin/env python3
"""Extract the webfonts embedded in the Claude Design standalone export.

The export bundles Google Fonts subsets (woff2) as base64 in a manifest block.
We pull them out so the site can self-host them instead of calling out to
fonts.googleapis.com on every pageview.

Run: python scripts/tools/extract_fonts.py
"""
import base64
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "assets" / "logo" / "source" / "cortexplor-logo-export.html"
OUT = ROOT / "assets" / "fonts"

SLUG = {"Space Grotesk": "space-grotesk", "IBM Plex Mono": "ibm-plex-mono"}

# PT/EN/ES only ever need these two subsets; the rest would be dead weight in git.
KEEP = {"latin", "latin-ext"}


def load_bundle(path):
    text = path.read_text(encoding="utf-8")
    manifest = json.loads(re.search(r'<script type="__bundler/manifest">(.*?)</script>', text, re.S).group(1))
    template = json.loads(re.search(r'<script type="__bundler/template">(.*?)</script>', text, re.S).group(1))
    return manifest, template


def parse_faces(template):
    faces = []
    for block in re.findall(r"@font-face\s*\{(.*?)\}", template, re.S):
        faces.append({
            "family": re.search(r"font-family: '([^']+)'", block).group(1),
            "weight": int(re.search(r"font-weight: (\d+)", block).group(1)),
            "uuid": re.search(r'src: url\("([^"]+)"\)', block).group(1),
            "range": re.search(r"unicode-range: ([^;]+);", block).group(1).strip(),
        })
    return faces


def subset_name(unicode_range):
    head = unicode_range.split(",")[0].strip()
    return {
        "U+0000-00FF": "latin",
        "U+0100-02BA": "latin-ext",
        "U+0102-0103": "vietnamese",
        "U+0301": "cyrillic",
        "U+0460-052F": "cyrillic-ext",
        "U+0370-0377": "greek",
        "U+1F00-1FFF": "greek-ext",
    }.get(head, head.lower().replace("+", "").replace("-", "_"))


def main():
    manifest, template = load_bundle(SRC)
    OUT.mkdir(parents=True, exist_ok=True)
    written, css = {}, []

    for face in parse_faces(template):
        family = face["family"]
        subset = subset_name(face["range"])
        if subset not in KEEP:
            continue
        name = f"{SLUG[family]}-{subset}.woff2"
        if face["uuid"] not in written:
            (OUT / name).write_bytes(base64.b64decode(manifest[face["uuid"]]["data"]))
            written[face["uuid"]] = name
        css.append((family, subset, written[face["uuid"]], face["range"], face["weight"]))

    # One @font-face per file. Both families ship as variable fonts here, so we
    # declare the full weight range instead of Google's per-weight duplicates.
    seen = set()
    lines = ["/* Generated by scripts/tools/extract_fonts.py - do not edit by hand. */", ""]
    for family, subset, filename, urange, _weight in css:
        if filename in seen:
            continue
        seen.add(filename)
        lines += [
            "@font-face {",
            f"  font-family: '{family}';",
            "  font-style: normal;",
            "  font-weight: 300 700;",
            "  font-display: swap;",
            f"  src: url('../fonts/{filename}') format('woff2');",
            f"  unicode-range: {urange};",
            "}",
            "",
        ]
    (ROOT / "assets" / "css" / "fonts.css").write_text("\n".join(lines), encoding="utf-8")

    total = sum((OUT / n).stat().st_size for n in set(written.values()))
    print(f"{len(set(written.values()))} font files -> assets/fonts/ ({total/1024:.1f} KB)")
    print("assets/css/fonts.css written")


if __name__ == "__main__":
    main()
